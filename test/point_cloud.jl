using Random

# Generate a rectangular point cloud, optionally with a perturbation in the point positions
# and rotated by `rotation_angle` degrees (see `rotation_matrix` below).
# The bounding box of the unperturbed lattice starts at 1 in each dimension, even when
# the lattice is rotated.
function point_cloud(n_points_per_dimension, search_radius;
                     seed = 1, perturbation_factor_position = 1.0, rotation_angle = 0,
                     shuffle = false, sort = !shuffle)
    # Fixed seed to ensure reproducibility
    rng = Random.Xoshiro(seed)

    n_dims = length(n_points_per_dimension)
    coordinates = Array{Float64}(undef, n_dims, prod(n_points_per_dimension))
    cartesian_indices = CartesianIndices(n_points_per_dimension)

    # Extra data structures for the sorting code below
    cell_coords = Vector{SVector{n_dims, Int}}(undef, size(coordinates, 2))
    cell_size = ntuple(dim -> search_radius, n_dims)

    # Rotate around the center of the lattice. The bounding box of the rotated lattice
    # is then centered around the origin, so we shift by half its size
    # to move its lower corner to 1.
    rotation = rotation_matrix(rotation_angle, Val(n_dims))
    lattice_size = SVector(Float64.(Tuple(n_points_per_dimension)) .- 1)
    center = 1 .+ lattice_size / 2
    offset = 1 .+ abs.(rotation) * lattice_size / 2

    for i in axes(coordinates, 2)
        point_coords = SVector(Float64.(Tuple(cartesian_indices[i])))
        point_coords = rotation * (point_coords - center) + offset

        # A standard deviation of 0.05 in the particle coordinates
        # corresponds to a standard deviation of 2 in the number of neighbors for a 300 x 100
        # grid, 1.6 for a 600 x 200 grid and 1.26 for a 1200 x 400 grid.
        # This is consistent with the standard deviation in a vortex street simulation.
        # The benchmark results are also consistent with the timer output of the simulation.
        point_coords += perturbation_factor_position * 0.05 *
                        randn(rng, typeof(point_coords))

        coordinates[:, i] .= point_coords
        cell_coords[i] = PointNeighbors.nonperiodic_cell_coords(point_coords, nothing,
                                                                cell_size) .+ 1
    end

    # Sort by the cell coordinates of the perturbed points.
    if sort
        if shuffle
            throw(ArgumentError("cannot sort and shuffle at the same time"))
        end

        # Sort by Z index (with `using Morton`)
        # permutation = sortperm(cell_coords, by = c -> cartesian2morton(c))

        permutation = sortperm(cell_coords)
        coordinates .= coordinates[:, permutation]
    elseif shuffle
        # Sort randomly
        permutation = Random.shuffle(rng, axes(coordinates, 2))
        coordinates .= coordinates[:, permutation]
    end

    return coordinates
end

# Size of the bounding box of the unperturbed point cloud generated by `point_cloud`
# with the given `rotation_angle`, in units of the point spacing.
function point_cloud_size(n_points_per_dimension; rotation_angle = 0)
    n_dims = length(n_points_per_dimension)
    rotation = rotation_matrix(rotation_angle, Val(n_dims))
    lattice_size = SVector(Float64.(Tuple(n_points_per_dimension)) .- 1)

    return abs.(rotation) * lattice_size .+ 1
end

# Rotation by `angle` degrees. In 3D, rotate around the z-axis and then around the x-axis,
# so that no lattice axis is aligned with a coordinate axis anymore.
# In 1D, there is nothing to rotate.
# The matrices are constructed column by column as static matrices.
rotation_matrix(angle, ::Val{1}) = hcat(SVector(1.0))

function rotation_matrix(angle, ::Val{2})
    s, c = sincosd(angle)

    return hcat(SVector(c, s), SVector(-s, c))
end

function rotation_matrix(angle, ::Val{3})
    s, c = sincosd(angle)
    rotation_z = hcat(SVector(c, s, 0.0), SVector(-s, c, 0.0), SVector(0.0, 0.0, 1.0))
    rotation_x = hcat(SVector(1.0, 0.0, 0.0), SVector(0.0, c, s), SVector(0.0, -s, c))

    return rotation_x * rotation_z
end

function perturb!(data, std_deviation; rng = Random.default_rng())
    for i in eachindex(data)
        data[i] += std_deviation * randn(rng)
    end

    return data
end
