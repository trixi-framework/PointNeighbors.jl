# SIMD-vectorized version of `foreach_point` for the `GridNeighborhoodSearch` with a
# `FullGridCellList` on CPUs.
# This is used when `foreach_point` is called with `simd = Val(true)`.
#
# The main ideas are:
# - The points of each cell are split into blocks of `BLOCK_SIZE` consecutive entries
#   of the cell in the cell list.
# - For all blocks of a cell at once, a cheap first pass (the filter) over all blocks of the
#   neighboring cells (the candidates) finds out which candidates contain at least one
#   neighbor of each point. For every block of the cell and every candidate, this is stored
#   as a bit mask with one bit per point of the block.
# - For each point, `mapreduce_neighbor` then only visits the candidates with the bit of
#   this point set and computes all `BLOCK_SIZE` points of a candidate at once with SIMD
#   instructions. The results of points that are not neighbors are discarded.
# - Each SIMD lane keeps its own partial result across all candidates,
#   and the lanes are only reduced once per point.
#
# The points of a block are generally not contiguous in memory, so the values of the
# neighbors are loaded through the cell list (gather instructions).
#
# The points of the outer loop are taken from a cell list of the system points on the same
# grid as the cell list of the neighbor points. Therefore, this is only implemented for the
# point set pairs of a `CombinedGridNeighborhoodSearch`, where each point set has its own
# cell list on the same grid.
const BLOCK_SIZE = 8

# LLVMLoopInfo handles LLVM key/value metadata, while Julia's independence marker is a bare
# `julia.ivdep` metadata node. This wrapper adds that node to the metadata generated by
# `@loopinfo`, allowing both the no-alias promise and the vector width hints to be used.
macro ivdep(ex)
    loop = macroexpand(__module__, ex)
    loop.head === :for || error("@ivdep needs a loop macro expanding to a for loop")
    metadata = loop.args[2].args[end]
    metadata.head === :loopinfo || error("wrapped loop has no loop metadata")
    push!(metadata.args, Symbol("julia.simdloop"), Symbol("julia.ivdep"))
    return esc(loop)
end

# A `GridNeighborhoodSearch` with a `FullGridCellList` with `DynamicVectorOfVectors`
# backend on CPUs without periodicity.
const BlockedGridNHS = GridNeighborhoodSearch{<:Any, <:Any,
                                              <:FullGridCellList{<:DynamicVectorOfVectors{<:Any,
                                                                                          <:Array}},
                                              <:Any, Nothing}

# The points of all cells are stored in `cell_entries(cells)`. The points of a cell are
# the `n_points_in_cell(cells, cell)` consecutive entries starting at the linear index
# `first_entry_in_cell(cells, cell)`.
@inline cell_entries(cells::DynamicVectorOfVectors) = cells.backend

@propagate_inbounds function n_points_in_cell(cells::DynamicVectorOfVectors, cell)
    return cells.lengths[cell]
end

@inline function first_entry_in_cell(cells::DynamicVectorOfVectors, cell)
    return (cell - 1) * size(cells.backend, 1) + 1
end

# Number of points that are stored in all cells.
function n_points_in_cells(cells)
    return sum(cell -> Int(@inbounds n_points_in_cell(cells, cell)), eachindex(cells),
               init = 0)
end

function max_points_in_cells(cells)
    return maximum(cell -> Int(@inbounds n_points_in_cell(cells, cell)), eachindex(cells),
                   init = 0)
end

# Scratch arrays of one task for the filter of one cell.
struct BlockFilter
    # Linear index of the first entry of each candidate in the entries of the neighbor
    # cell list.
    candidate_first_entry :: Vector{Int}
    candidate_n_points    :: Vector{Int32}
    # One column per block of the cell with one byte per candidate.
    # Bit `lane - 1` is set if point `lane` of the block has a neighbor in the candidate.
    masks::Matrix{UInt8}
end

function BlockFilter(max_points_system_cell::Integer, max_points_neighbor_cell::Integer,
                     ndims::Integer)
    max_blocks = cld(max_points_system_cell, BLOCK_SIZE)
    max_candidates = 3^ndims * cld(max_points_neighbor_cell, BLOCK_SIZE)

    # The masks are loaded in chunks of 64 candidates.
    masks = Matrix{UInt8}(undef, 64 * cld(max_candidates, 64), max_blocks)

    return BlockFilter(Vector{Int}(undef, max_candidates),
                       Vector{Int32}(undef, max_candidates), masks)
end

# The neighbors of a single point, which is point `lane` of block `block` of its cell.
struct NeighborBlocksOfPoint{NC, NHS, P, PC, E}
    neighbor_coords     :: NC
    neighborhood_search :: NHS
    point               :: P
    point_coords        :: PC
    filter              :: BlockFilter
    block               :: Int
    lane                :: Int
    n_candidates        :: Int
    entries             :: E
end

# The points of the outer loop are taken from the cell list of the system point set.
@inline function foreach_point_inner(f, system_coords, neighbor_coords,
                                     neighborhood_search::PointSetPairSearch{<:BlockedGridNHS},
                                     parallelization_backend::AbstractThreadingBackend,
                                     points, safe::Val, simd::Val{true})
    (; system_search, neighbor_search) = neighborhood_search

    foreach_point_blocked(f, system_coords, neighbor_coords, system_search,
                          neighbor_search, parallelization_backend, points, safe)
end

# Blocked loop over all `points` with the neighbors in the cell list of `neighbor_search`.
# The points of the outer loop are taken from the cell list of `system_search`, which must
# use the same grid as `neighbor_search`. Points of this cell list that are not in `points`
# are skipped. All points in `points` must be in this cell list.
@inline function foreach_point_blocked(f, system_coords, neighbor_coords, system_search,
                                       neighbor_search, parallelization_backend, points,
                                       safe)
    neighbor_cells = neighbor_search.cell_list.cells

    if eltype(system_coords) != eltype(neighbor_coords)
        throw(ArgumentError("with `simd = Val(true)`, `system_coords` and " *
                            "`neighbor_coords` must have the same element type"))
    end

    # The SIMD loads of the entries in `mapreduce_neighbor` require at least
    # `BLOCK_SIZE` entries.
    if ndims(neighbor_search) > 3 || length(cell_entries(neighbor_cells)) < BLOCK_SIZE
        return foreach_point_inner(f, system_coords, neighbor_coords, neighbor_search,
                                   parallelization_backend, points, safe, Val(false))
    end

    point_mask = create_point_mask(points, size(system_coords, 2),
                                   parallelization_backend)
    n_points_blocked = foreach_point_blocked_inner(f, system_coords, neighbor_coords,
                                                   system_search, neighbor_search,
                                                   parallelization_backend, point_mask,
                                                   safe)

    # The cell list contains every point only once, so if fewer points than in `points`
    # have been computed, some points in `points` are not in the cell list.
    if n_points_blocked != length(points)
        throw(ArgumentError("with `simd = Val(true)`, all `points` must be in the cell " *
                            "list of the system points"))
    end

    return nothing
end

# Returns the number of points for which `f` has been called.
function foreach_point_blocked_inner(f::T, system_coords, neighbor_coords, system_search,
                                     neighbor_search, parallelization_backend, point_mask,
                                     ::Val{SAFE}) where {T, SAFE}
    max_points_system = max_points_in_cells(system_search.cell_list.cells)
    max_points_neighbor = max_points_in_cells(neighbor_search.cell_list.cells)
    filters = [BlockFilter(max_points_system, max_points_neighbor, ndims(neighbor_search))
               for _ in 1:n_tasks(parallelization_backend)]
    n_points_task = zeros(Int, n_tasks(parallelization_backend))

    # Each cell only writes to its own points, so all cells can be processed in parallel.
    foreach_cell_chunk(system_search, parallelization_backend) do task, cell_range
        n_points = foreach_point_in_cells(f, system_coords, neighbor_coords,
                                          system_search, neighbor_search, cell_range,
                                          @inbounds(filters[task]), point_mask,
                                          Val(SAFE))
        @inbounds n_points_task[task] += n_points
    end

    return sum(n_points_task)
end

# Mask to check if a point is in `points`.
# A range can be used directly, so that no mask has to be created.
@inline create_point_mask(points::AbstractUnitRange, n_points,
                          parallelization_backend) = points

function create_point_mask(points, n_points, parallelization_backend)
    mask = fill(false, n_points)

    # `points` has been bounds checked in `foreach_point`.
    @threaded parallelization_backend for point in points
        @inbounds mask[point] = true
    end

    return mask
end

@inline is_in_points(points::AbstractUnitRange, point) = point in points

# `point` must be in bounds of the mask.
@inline is_in_points(mask::Vector{Bool}, point) = @inbounds mask[point]

@inline n_tasks(::SerialBackend) = 1
@inline n_tasks(_) = Threads.nthreads()

# Call `f(task, cell_range)` for chunks of whole rows of cells in parallel.
# The tasks take the chunks one after another, so that a task with more points in its
# chunks takes fewer chunks, and all tasks work on neighboring rows at the same time,
# which share their neighbor cells in the cache.
@inline function foreach_cell_chunk(f::F, neighborhood_search,
                                    parallelization_backend) where {F}
    (; cells, linear_indices) = neighborhood_search.cell_list
    n_cells = length(cells)
    row_length = size(linear_indices, 1)
    cells_per_chunk = row_length * cld(100, row_length)
    n_chunks = cld(n_cells, cells_per_chunk)
    next_chunk = Threads.Atomic{Int}(1)

    @threaded parallelization_backend for task in 1:n_tasks(parallelization_backend)
        while (chunk = Threads.atomic_add!(next_chunk, 1)) <= n_chunks
            cell_range = ((chunk - 1) * cells_per_chunk + 1):min(chunk * cells_per_chunk,
                                                                 n_cells)
            f(task, cell_range)
        end
    end
end

# Returns the number of points for which `f` has been called.
@inline function foreach_point_in_cells(f, system_coords, neighbor_coords, system_search,
                                        neighbor_search, cell_range, filter, point_mask,
                                        ::Val{SAFE}) where {SAFE}
    system_cells = system_search.cell_list.cells
    (; cells, linear_indices) = neighbor_search.cell_list
    (; candidate_first_entry, candidate_n_points) = filter
    system_entries = cell_entries(system_cells)
    entries = cell_entries(cells)
    NDIMS = ndims(neighbor_search)
    offsets = neighbor_cell_offsets(linear_indices, Val(NDIMS))
    n_points_computed = 0

    for cell in cell_range
        n_points_cell = Int(@inbounds n_points_in_cell(system_cells, cell))
        n_points_cell > 0 || continue
        first_entry_cell = Int(@inbounds first_entry_in_cell(system_cells, cell))

        # All points of the cell are bounds checked here.
        if SAFE
            for entry in first_entry_cell:(first_entry_cell + n_points_cell - 1)
                checkbounds(system_coords, NDIMS, system_entries[entry])
            end
        end

        # All blocks of the neighboring cells are candidates.
        # All points of the candidates are bounds checked here.
        n_candidates = 0
        for offset in offsets
            neighbor_cell = cell + offset
            SAFE && checkbounds(cells, neighbor_cell)
            n_points_neighbor_cell = Int(@inbounds n_points_in_cell(cells, neighbor_cell))
            first_entry_neighbor_cell = Int(@inbounds first_entry_in_cell(cells,
                                                                          neighbor_cell))
            last_entry_neighbor_cell = first_entry_neighbor_cell + n_points_neighbor_cell -
                                       1

            for first_entry in first_entry_neighbor_cell:BLOCK_SIZE:last_entry_neighbor_cell
                n_points_block = min(BLOCK_SIZE, last_entry_neighbor_cell - first_entry + 1)
                n_candidates += 1
                @inbounds candidate_first_entry[n_candidates] = first_entry
                @inbounds candidate_n_points[n_candidates] = n_points_block

                if SAFE
                    for entry in first_entry:(first_entry + n_points_block - 1)
                        checkbounds(neighbor_coords, NDIMS, entries[entry])
                    end
                end
            end
        end

        find_neighbor_masks!(filter, system_coords, neighbor_coords, neighbor_search,
                             system_entries, entries, first_entry_cell, n_points_cell,
                             n_candidates)

        for block in 1:cld(n_points_cell, BLOCK_SIZE)
            first_entry = first_entry_cell + (block - 1) * BLOCK_SIZE
            n_points_block = min(BLOCK_SIZE, first_entry_cell + n_points_cell - first_entry)

            for lane in 1:n_points_block
                point = Int(@inbounds system_entries[first_entry + lane - 1])

                # Skip points of the cell list that are not in `points`.
                # All points of the cell have been bounds checked above.
                is_in_points(point_mask, point) || continue
                n_points_computed += 1

                point_coords = @inbounds extract_svector(system_coords, Val(NDIMS), point)

                neighbors = NeighborBlocksOfPoint(neighbor_coords, neighbor_search, point,
                                                  point_coords, filter, block, lane,
                                                  n_candidates, entries)
                @inline f(point, neighbors)
            end
        end
    end

    return n_points_computed
end

# Offsets of the linear indices of all neighboring cells, including the cell itself.
@inline function neighbor_cell_offsets(linear_indices, ::Val{NDIMS}) where {NDIMS}
    n_cells = size(linear_indices)
    strides = ntuple(dim -> prod(ntuple(i -> i < dim ? n_cells[i] : 1, Val(NDIMS))),
                     Val(NDIMS))

    return (sum(Tuple(offset) .* strides)
            for offset in CartesianIndices(ntuple(_ -> -1:1, Val(NDIMS))))
end

# For all blocks of the cell and all candidates, compute the masks of the points of the
# block that have at least one neighbor in the candidate.
# Up to four blocks are processed at once, so that the coordinates of each candidate
# are only loaded once for all of them.
@inline function find_neighbor_masks!(filter, system_coords, neighbor_coords,
                                      neighborhood_search, system_entries, entries,
                                      first_entry_cell, n_points_cell, n_candidates)
    # The filter computes the distances like `mapreduce_neighbor`, but possibly with
    # different rounding. A slightly larger search radius makes sure that the filter
    # never misses a neighbor.
    T = eltype(neighbor_coords)
    rounding_error = 16 * max(eps(T), eps(eltype(neighborhood_search)))
    filter_radius2 = T(search_radius(neighborhood_search)^2 * (1 + rounding_error))

    n_blocks = cld(n_points_cell, BLOCK_SIZE)
    for first_block in 1:4:n_blocks
        n_blocks_group = min(4, n_blocks - first_block + 1)
        args = (filter, system_coords, neighbor_coords, filter_radius2, system_entries,
                entries, first_entry_cell, n_points_cell, n_candidates, first_block,
                Val(ndims(neighborhood_search)))
        if n_blocks_group == 4
            filter_group!(Val(4), args...)
        elseif n_blocks_group == 3
            filter_group!(Val(3), args...)
        elseif n_blocks_group == 2
            filter_group!(Val(2), args...)
        else
            filter_group!(Val(1), args...)
        end
    end

    # Zero the masks of the remaining candidates of the last chunk of 64 candidates,
    # which are loaded in `mapreduce_neighbor`.
    for block in 1:n_blocks, candidate in (n_candidates + 1):(64 * cld(n_candidates, 64))
        @inbounds filter.masks[candidate, block] = zero(UInt8)
    end
end

@inline function filter_group!(::Val{N_BLOCKS}, filter, system_coords, neighbor_coords,
                               filter_radius2, system_entries, entries, first_entry_cell,
                               n_points_cell, n_candidates, first_block,
                               ::Val{NDIMS}) where {N_BLOCKS, NDIMS}
    (; candidate_first_entry, candidate_n_points, masks) = filter
    V = Vec{BLOCK_SIZE, eltype(neighbor_coords)}

    # Coordinates of the points of the blocks of the group.
    block_coords = ntuple(@inline(i -> block_coords_simd(system_coords, system_entries,
                                                         first_entry_cell, n_points_cell,
                                                         first_block + i - 1, Val(NDIMS))),
                          Val(N_BLOCKS))

    for candidate in 1:n_candidates
        first_entry = @inbounds candidate_first_entry[candidate]
        n_points = Int(@inbounds candidate_n_points[candidate])

        # Minimum squared distance of each lane to the points of the candidate.
        min_distance2 = ntuple(_ -> V(Inf), Val(N_BLOCKS))
        for neighbor_lane in 1:BLOCK_SIZE
            # Lanes after the last point of the candidate repeat the last point.
            neighbor = Int(@inbounds entries[first_entry + min(neighbor_lane, n_points) - 1])
            neighbor_coords_ = ntuple(@inline(dim -> @inbounds(neighbor_coords[dim,
                                                                               neighbor])),
                                      Val(NDIMS))

            min_distance2 = update_min_distance2(min_distance2, block_coords,
                                                 neighbor_coords_)
        end

        for i in 1:N_BLOCKS
            mask = bitmask(min_distance2[i] <= filter_radius2)
            @inbounds masks[candidate, first_block + i - 1] = mask % UInt8
        end
    end
end

# Coordinates of the points of block `block` of the cell as one SIMD vector per dimension.
# Lanes after the last point of the cell repeat the last point.
# All points of the cell have been bounds checked in `foreach_point_in_cells`.
@inline function block_coords_simd(coords, entries, first_entry_cell, n_points_cell, block,
                                   ::Val{NDIMS}) where {NDIMS}
    first_lane = (block - 1) * BLOCK_SIZE
    points = ntuple(@inline(function (lane)
                                entry = first_entry_cell +
                                        min(first_lane + lane, n_points_cell) - 1
                                return Int(@inbounds entries[entry])
                            end), Val(BLOCK_SIZE))

    return ntuple(@inline(function (dim)
                              values = ntuple(@inline(lane -> @inbounds(coords[dim,
                                                                               points[lane]])),
                                              Val(BLOCK_SIZE))
                              return Vec{BLOCK_SIZE, eltype(coords)}(values)
                          end), Val(NDIMS))
end

# `min.(min_distance2, distance2)` for all blocks of the group.
# This must be a separate function, so that `min_distance2` is not captured and
# reassigned in a closure, which would make it a `Core.Box`.
@inline function update_min_distance2(min_distance2::NTuple{N_BLOCKS}, block_coords,
                                      neighbor_coords::NTuple{NDIMS}) where {N_BLOCKS,
                                                                             NDIMS}
    return ntuple(@inline(function (i)
                              distance2 = zero(min_distance2[i])
                              for dim in 1:NDIMS
                                  pos_diff = block_coords[i][dim] - neighbor_coords[dim]
                                  distance2 = muladd(pos_diff, pos_diff, distance2)
                              end

                              # A select instead of `min`, which would handle NaNs with
                              # extra instructions.
                              return vifelse(distance2 < min_distance2[i], distance2,
                                             min_distance2[i])
                          end), Val(N_BLOCKS))
end

@inline function mapreduce_neighbor(f, op, neighbors::NeighborBlocksOfPoint; init)
    (; filter, block, lane, n_candidates) = neighbors
    (; candidate_first_entry, candidate_n_points, masks) = filter

    # Keep one partial result per SIMD lane across the complete neighbor traversal.
    # This allows LLVM to keep the partial results in vector registers and to perform the
    # reductions over the lanes only once per point instead of once per candidate.
    # The partial results are stored with the lanes as contiguous dimension
    # (`lane_results[lane, component]`), so that each component of the result is a vector.
    init_flat = flatten(init)
    ELTYPE = eltype(promote(init_flat...))
    lane_results = MMatrix{BLOCK_SIZE, length(init_flat), ELTYPE}(undef)
    for neighbor_lane in 1:BLOCK_SIZE
        flatten!(lane_results, neighbor_lane, init)
    end

    lane_bit = UInt8(1) << (lane - 1)
    for first_candidate in 1:64:n_candidates
        # Bit `k - 1` is set if candidate `first_candidate + k - 1` contains a neighbor
        # of this point. The masks of all 64 candidates are loaded at once.
        chunk_masks = GC.@preserve masks vload(Vec{64, UInt8},
                                               pointer(masks,
                                                       first_candidate +
                                                       (block - 1) *
                                                       size(masks, 1)))
        bits = bitmask((chunk_masks & lane_bit) != zero(UInt8))

        while bits != 0
            candidate = first_candidate + trailing_zeros(bits)
            bits &= bits - one(bits)

            first_entry = @inbounds candidate_first_entry[candidate]
            n_points = @inbounds candidate_n_points[candidate]
            candidate_neighbors!(f, op, lane_results, init, neighbors, first_entry,
                                 n_points)
        end
    end

    # Reduce the partial results of all lanes in a tree. In each step, the upper half
    # of the remaining lanes is combined with the lower half, which is a SIMD operation
    # on contiguous lanes. Reducing lane after lane would load each lane with gathers.
    reduce_lanes!(op, init, lane_results, Val(BLOCK_SIZE ÷ 2))
    reduce_lanes!(op, init, lane_results, Val(BLOCK_SIZE ÷ 4))
    reduce_lanes!(op, init, lane_results, Val(BLOCK_SIZE ÷ 8))

    return @inbounds unflatten(init, lane_results, 1)
end

# Compute all points of the candidate of `n_points` entries starting at `first_entry`
# at once with SIMD instructions and update the partial results of all lanes.
@inline function candidate_neighbors!(f, op, lane_results, init, neighbors, first_entry,
                                      n_points)
    (; neighbor_coords, neighborhood_search, point, point_coords, entries) = neighbors
    NDIMS = ndims(neighborhood_search)
    search_radius2 = search_radius(neighborhood_search)^2

    # Shift the lanes to the left if they would go beyond the last entry.
    # Then, the entries of all lanes can always be loaded with a single SIMD load.
    first_lane_entry = min(first_entry, length(entries) - BLOCK_SIZE + 1)

    # Entries outside of the candidate might not contain valid points.
    # These lanes use the first point of the candidate, and their results are discarded.
    first_point = @inbounds entries[first_entry]

    # Each iteration only writes to its own row of `lane_results`.
    # Always computing `BLOCK_SIZE` lanes allows LLVM to keep `lane_results` in registers.
    @ivdep @loopinfo vectorize vectorwidth=8 for neighbor_lane in 1:BLOCK_SIZE
        entry = first_lane_entry + neighbor_lane - 1
        in_candidate = first_entry <= entry < first_entry + n_points

        # All points of the candidates have been bounds checked
        # in `foreach_point_in_cells`.
        neighbor = Int(ifelse(in_candidate, @inbounds(entries[entry]), first_point))
        neighbor_point_coords = @inbounds extract_svector(neighbor_coords, Val(NDIMS),
                                                          neighbor)

        pos_diff = convert.(eltype(neighborhood_search),
                            point_coords - neighbor_point_coords)
        distance2 = dot(pos_diff, pos_diff)
        is_neighbor = in_candidate & (distance2 <= search_radius2)

        # Use a valid dummy distance for points that are not neighbors.
        # Their results are discarded below.
        distance = Base.FastMath.sqrt_fast(ifelse(is_neighbor, distance2, search_radius2))

        value = @inline f(point, neighbor, pos_diff, distance)

        # Mask the result component by component. Masking the result as a whole
        # prevents the vectorization for some functions.
        lane_result = @inbounds unflatten(init, lane_results, neighbor_lane)
        updated = flatten(@inline op(lane_result, value))
        masked = map((new, old) -> ifelse(is_neighbor, new, old),
                     updated, flatten(lane_result))
        @inbounds flatten!(lane_results, neighbor_lane, masked)
    end

    return lane_results
end

# `lane_results[lane, :] = op(lane_results[lane, :], lane_results[lane + width, :])`
# for all `lane` in `1:width`.
@inline function reduce_lanes!(op, init, lane_results, ::Val{width}) where {width}
    @ivdep @loopinfo vectorize for lane in 1:width
        a = @inbounds unflatten(init, lane_results, lane)
        b = @inbounds unflatten(init, lane_results, lane + width)
        @inbounds flatten!(lane_results, lane, @inline op(a, b))
    end

    return lane_results
end

# Flatten nested tuples and `SVector`s of numbers into a flat tuple of numbers.
# This is used to store one partial result per SIMD lane with the lanes as contiguous
# dimension, independent of the structure of the result.
@inline flatten(x::Number) = (x,)
@inline flatten(x::SVector) = flatten(Tuple(x))
@inline flatten(::Tuple{}) = ()
@inline flatten(x::Tuple) = (flatten(first(x))..., flatten(Base.tail(x))...)

# Store the flattened `x` in `lane_results[lane, :]`.
@inline function flatten!(lane_results, lane, x)
    x_flat = flatten(x)
    ntuple(Val(length(x_flat))) do component
        @inbounds lane_results[lane, component] = x_flat[component]
        return nothing
    end

    return lane_results
end

# Inverse of `flatten!`: Load `lane_results[lane, :]` into an object with the same
# structure and types as `template`.
@propagate_inbounds function unflatten(template, lane_results, lane)
    return first(unflatten(template, lane_results, lane, 1))
end

# Return the object and the next component index.
@propagate_inbounds function unflatten(template::Number, lane_results, lane, component)
    return convert(typeof(template), lane_results[lane, component]), component + 1
end

@propagate_inbounds function unflatten(template::SVector, lane_results, lane, component)
    values, next_component = unflatten(Tuple(template), lane_results, lane, component)
    return SVector(values), next_component
end

@inline unflatten(::Tuple{}, lane_results, lane, component) = (), component

@propagate_inbounds function unflatten(template::Tuple, lane_results, lane, component)
    first_, component_ = unflatten(first(template), lane_results, lane, component)
    tail, next_component = unflatten(Base.tail(template), lane_results, lane, component_)
    return (first_, tail...), next_component
end
